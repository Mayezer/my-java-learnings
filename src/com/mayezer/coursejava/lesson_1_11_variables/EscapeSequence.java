package com.mayezer.coursejava.lesson_1_11_variables;

public class EscapeSequence {

    public static void main(String[] args) {

        // "Hello, World!"
        System.out.print("\"Hello, World!\"\n\r"); // \n\r Pula para a linha de baixo e substitui o ln do final do print.

        // 1\4
        System.out.println("1\\4");
    }
}
