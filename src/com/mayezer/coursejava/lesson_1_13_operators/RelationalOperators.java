package com.mayezer.coursejava.lesson_1_13_operators;

public class RelationalOperators {

    public static void main(String[] args) {

        int value01 = 1;
        int value02 = 2;

        System.out.println(value01 == value02);
        System.out.println(value01 != value02);
        System.out.println(value01 > value02);
        System.out.println(value01 < value02);
        System.out.println(value01 >= value02);
        System.out.println(value01 <= value02);
        // Resultado vai ser um boolean: true ou false
    }
}
