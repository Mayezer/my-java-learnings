package com.mayezer.cursojava.aula11;

public class IntegerVariables {

    public static void main(String[] args) {

        byte age01 = 20;
        short age02 = 21;
        int age03 = 22;
        long age04 = 23;

        System.out.println("Variable value 01: " + age01);
        System.out.println("Variable value 02: " + age02);
        System.out.println("Variable value 03: " + age03);
        System.out.println("Variable value 04: " + age04);
    }
}
