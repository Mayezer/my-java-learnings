package com.mayezer.cursojava.aula10;

public class Variables {

    public static void main(String[] args) {
        int age = 26;
        String name = "Mayezer";
        String myCatsName = "Tico"; // Java convention
        String year2026 = "2026";

        System.out.println("Age: " + age);
        System.out.println("Name: " + name);
        System.out.println("My cat's name: " + myCatsName);
        System.out.println("This year: " + year2026);
    }
}
